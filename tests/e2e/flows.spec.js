test('گزارش: بازه‌ها، نمودار و خروجی Excel', async ({ page }, info) => {
  await startDemo(page)
  await go(page, 'reports')
  for (const range of ['این ماه', '۳ ماه', 'امسال', 'همه']) {
    await page.getByRole('group', { name: 'بازه‌ی گزارش' }).getByRole('button', { name: range, exact: true }).click()
    await expect(page.locator('.headline__value').first()).not.toHaveText('—')
  }
  const columns = page.locator('.chart__col:visible')
  await expect(columns).toHaveCount(info.project.name === 'mobile' ? 6 : 12)
  await columns.first().click()
  await expect(columns.first()).toHaveAttribute('aria-pressed', 'true')
  await page.getByText('نمایش جدولی').click()
  await expect(page.locator('.chart__table tbody tr')).toHaveCount(12)

  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'خروجی Excel' }).click()])
  expect(download.suggestedFilename()).toMatch(/^ravon-all-.*\.xlsx$/)
  const path = info.outputPath('export.xlsx')
  await download.saveAs(path)
  expect(readFileSync(path).subarray(0, 2).toString()).toBe('PK')
})

