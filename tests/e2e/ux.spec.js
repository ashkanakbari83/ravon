test('نصب برنامه: دکمه فقط وقتی مرورگر اجازه بده', async ({ page }) => {
  await startFresh(page)
  await go(page, 'settings')
  const button = page.getByRole('button', { name: 'نصب رَوون' })
  await expect(button).toHaveCount(0)
  await page.evaluate(() => {
    const event = new Event('beforeinstallprompt', { cancelable: true })
    event.prompt = () => ((window.__installed = true), Promise.resolve())
    window.dispatchEvent(event)
  })
  await button.click()
  expect(await page.evaluate(() => window.__installed)).toBe(true)
  await expect(button).toHaveCount(0)
})
