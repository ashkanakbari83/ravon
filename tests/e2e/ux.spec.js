test('حذف پرداخت، زمان و خروجی با برگردون', async ({ page }) => {
  await startFresh(page)
  await quickAdd(page, { title: 'موشن', client: 'نوا', amount: '1000000' })
  await go(page, 'projects')
  await page.locator('.row__link').click()
  await page.getByRole('button', { name: 'ثبت دریافتی' }).click()
  await sheet(page).getByRole('button', { name: 'ثبت دریافتی' }).click()
  await page.getByRole('button', { name: '۱ ساعت' }).click()
  await page.getByLabel('اسم خروجی').fill('نسخه‌ی عمودی')
  await page.getByRole('button', { name: 'افزودن', exact: true }).click()
  const before = await state(page)

  for (const [card, message] of [['money', 'پرداخت حذف شد'], ['time', 'زمان حذف شد'], ['items', 'خروجی حذف شد']]) {
    await page.locator(`[aria-labelledby="${card}-title"]`).getByRole('button', { name: /^حذف/ }).click()
    const note = toast(page).locator('.toast', { hasText: message })
    await note.getByRole('button', { name: 'برگردون' }).click()
    await expect(note).toHaveCount(0)
  }
  const after = await state(page)
  expect([after.payments, after.timeEntries, after.projects]).toEqual([before.payments, before.timeEntries, before.projects])
})

