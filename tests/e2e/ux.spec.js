test('برگشت از جزئیات: همون فیلتر و همون‌جای فهرست', async ({ page }) => {
  await startDemo(page)
  await go(page, 'projects')
  await page.getByRole('button', { name: /^همه/ }).click()
  const row = page.locator('.row__link').nth(20)
  await row.scrollIntoViewIfNeeded()
  const at = await page.evaluate(() => window.scrollY)
  expect(at).toBeGreaterThan(300)
  const url = page.url()
  await row.click()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(0)
  await page.locator('.back').click()
  await expect(page).toHaveURL(url)
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(at - 40)
  await page.locator('.row__link').nth(20).click()
  await page.goBack()
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(at - 40)
})

